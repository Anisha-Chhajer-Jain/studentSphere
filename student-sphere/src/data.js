// Helper functions
export function getStudentById(id) {
  if (!id) return null;
  const query = id.toLowerCase();
  return students.find(
    (s) => s.id.toLowerCase() === query || s.studentCode.toLowerCase() === query
  ) || null;
}

export function getTrackData(deptSlug, trackSlug) {
  const dept = departments.find((d) => d.slug === deptSlug);
  if (!dept || !dept.tracks) return null;
  return dept.tracks.find((t) => t.slug === trackSlug) || null;
}
